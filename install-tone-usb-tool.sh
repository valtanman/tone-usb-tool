#!/usr/bin/env bash
# TONE USB Tool / TONE USB ツール (write ISO + forced wipe, one package)
#   install:   sudo bash install-tone-usb-tool.sh      uninstall: sudo bash install-tone-usb-tool.sh --uninstall
#   Language files (ja, en built in): add xx.lang to ~/.config/tone-usb/lang/ or /usr/local/share/tone-usb/lang/
set -eu
JA=0; case "${LC_ALL:-${LANG:-}}" in ja*) JA=1;; esac
say() { if [ $JA = 1 ]; then echo "$1"; else echo "$2"; fi; }
PREFIX=${TONE_PREFIX:-}
if [ -z "$PREFIX" ] && [ "$(id -u)" != 0 ]; then exec sudo -E bash "$0" "$@"; fi
FILES="usr/local/bin/tone-usb-flash usr/local/lib/tone-usb/usb-root usr/share/applications/tone-usb-flash.desktop usr/share/icons/hicolor/256x256/apps/tone-usb-flash.png usr/local/share/tone-usb/lang/ja.lang usr/local/share/tone-usb/lang/en.lang"
if [ "${1:-}" = --uninstall ]; then
  for f in $FILES; do rm -f "$PREFIX/$f"; done; rmdir "$PREFIX/usr/local/lib/tone-usb" "$PREFIX/usr/local/share/tone-usb/lang" "$PREFIX/usr/local/share/tone-usb" 2>/dev/null || true
  say "アンインスコしました。" "Uninstalled."; exit 0
fi
if [ -z "$PREFIX" ] && command -v apt-get >/dev/null; then
  for p in gdisk zenity util-linux rsync; do dpkg -s $p >/dev/null 2>&1 || apt-get install -y $p >/dev/null 2>&1 || say "任意パッケージを入れられませんでした: $p" "Could not install optional package: $p"; done
fi
mkdir -p "$PREFIX/"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | tar xz -C "$PREFIX/" --no-same-owner
chmod 755 "$PREFIX/usr/local/bin/tone-usb-flash" "$PREFIX/usr/local/lib/tone-usb/usb-root"
if [ -z "$PREFIX" ]; then
  command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -q /usr/share/icons/hicolor 2>/dev/null || true
  command -v update-desktop-database >/dev/null && update-desktop-database -q /usr/share/applications 2>/dev/null || true
fi
say "インスコしました。メニューの「TONE USB ツール」から起動できます(ISOを右クリックで開くこともできます)。" "Installed. Start \"TONE USB Tool\" from the menu (you can also right-click an ISO and open it with it)."
exit 0
